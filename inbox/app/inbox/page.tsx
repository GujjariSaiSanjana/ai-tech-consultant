import Link from "next/link";
import { getServices } from "../../src/services/container";
import { Badge } from "../../src/ui/components/badge";
import { DraftEditor } from "../../src/ui/components/draft-editor";
import { PostButton } from "../../src/ui/components/post-button";
import { WhyPanel } from "../../src/ui/components/why-panel";
import { relativeAge } from "../../src/ui/labels";
import { inboxItems, type InboxFilter, type InboxItem } from "../../src/ui/queries";

export const dynamic = "force-dynamic";

const FILTERS: Array<{ id: InboxFilter; label: string }> = [
  { id: "review", label: "Needs review" },
  { id: "auto", label: "Auto-sent" },
  { id: "done", label: "Done" },
  { id: "all", label: "All" },
];

function href(filter: InboxFilter, id?: string): string {
  return `/inbox?filter=${filter}${id ? `&id=${encodeURIComponent(id)}` : ""}`;
}

function StatusBadge({ item }: { item: InboxItem }) {
  switch (item.email.status) {
    case "new":
      return <Badge>Not drafted</Badge>;
    case "drafted":
      return item.draft?.needs_review ? <Badge tone="amber">Check flags</Badge> : <Badge tone="blue">Ready to send</Badge>;
    case "auto_sent":
      return <Badge tone="green">Auto-sent</Badge>;
    case "sent":
      return <Badge>Sent</Badge>;
    case "rejected":
      return <Badge tone="red">Rejected</Badge>;
  }
}

export default async function InboxPage({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const params = await searchParams;
  const filter = (FILTERS.find((f) => f.id === params.filter)?.id ?? "review") as InboxFilter;
  const services = getServices();
  const items = inboxItems(services, filter);
  const selectedId = typeof params.id === "string" ? params.id : items[0]?.email.id;
  const index = items.findIndex((i) => i.email.id === selectedId);
  const selected = index >= 0 ? items[index] : selectedId ? inboxItems(services, "all").find((i) => i.email.id === selectedId) : undefined;
  const newCount = services.repos.emails.listByStatus("new").length;
  const next = index >= 0 ? items[index + 1] : undefined;
  const prev = index > 0 ? items[index - 1] : undefined;
  const simulatedShown = items.some((i) => i.email.simulated);

  return (
    <div className="grid h-[calc(100vh-7.5rem)] grid-cols-1 gap-4 lg:grid-cols-[22rem_minmax(0,1fr)_24rem]">
      <aside className="flex min-h-0 flex-col rounded-lg border border-slate-200 bg-white">
        <div className="flex flex-wrap gap-1 border-b border-slate-200 p-2">
          {FILTERS.map((f) => (
            <Link
              key={f.id}
              href={href(f.id)}
              className={`rounded-md px-2 py-1 text-xs font-medium ${f.id === filter ? "bg-slate-900 text-white" : "text-slate-600 hover:bg-slate-100"}`}
            >
              {f.label}
            </Link>
          ))}
        </div>
        {newCount > 0 ? (
          <div className="border-b border-slate-200 p-2">
            <PostButton url="/api/process" label={`Draft replies for ${newCount} new email(s)`} pendingLabel="Drafting..." variant="primary" />
          </div>
        ) : null}
        {simulatedShown ? (
          <p className="border-b border-slate-200 bg-amber-50 px-3 py-1.5 text-xs text-amber-900">
            Items marked &ldquo;simulated&rdquo; were generated by the demo seed.
          </p>
        ) : null}
        <ul className="min-h-0 flex-1 divide-y divide-slate-100 overflow-y-auto">
          {items.length === 0 ? <li className="p-4 text-sm text-slate-500">Nothing here.</li> : null}
          {items.map((item) => (
            <li key={item.email.id}>
              <Link
                href={href(filter, item.email.id)}
                className={`block px-3 py-2.5 hover:bg-slate-50 ${item.email.id === selected?.email.id ? "bg-blue-50" : ""}`}
              >
                <div className="flex items-baseline justify-between gap-2">
                  <span className="truncate text-sm font-medium">{item.email.from_name}</span>
                  <span className="shrink-0 text-xs text-slate-500">{relativeAge(item.email.received_at)}</span>
                </div>
                <div className="truncate text-sm text-slate-700">{item.email.subject}</div>
                <div className="mt-1 flex flex-wrap items-center gap-1">
                  {item.kind ? <Badge tone="violet">{item.kind}</Badge> : null}
                  {item.classification ? (
                    <Badge tone={item.classification.confidence >= 0.85 ? "neutral" : "amber"}>{Math.round(item.classification.confidence * 100)}%</Badge>
                  ) : null}
                  <StatusBadge item={item} />
                  {item.email.simulated ? <Badge tone="amber">simulated</Badge> : null}
                  {item.email.split === "heldout" ? <Badge title="Held-out eval email: never used as an example">held out</Badge> : null}
                </div>
              </Link>
            </li>
          ))}
        </ul>
      </aside>

      <section className="flex min-h-0 flex-col overflow-y-auto rounded-lg border border-slate-200 bg-white p-4">
        {!selected ? (
          <p className="text-sm text-slate-500">Select an email.</p>
        ) : (
          <>
            <header className="mb-3">
              <h1 className="text-lg font-semibold">{selected.email.subject}</h1>
              <p className="text-sm text-slate-600">
                {selected.email.from_name} &lt;{selected.email.from_email}&gt; · {new Date(selected.email.received_at).toLocaleString("en-GB")}
              </p>
            </header>
            <details open className="mb-4 rounded-md border border-slate-200 bg-slate-50 p-3">
              <summary className="cursor-pointer text-xs font-semibold uppercase tracking-wide text-slate-500">Customer email</summary>
              <p className="mt-2 whitespace-pre-wrap text-sm text-slate-800">{selected.email.body}</p>
            </details>
            {selected.draft ? (
              <>
                <h2 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">
                  {selected.draft.status === "auto_sent" ? "Sent automatically" : selected.draft.status === "pending" ? "Draft reply" : "Reply"}
                </h2>
                <DraftEditor
                  key={selected.draft.id}
                  draftId={selected.draft.id}
                  draftText={selected.draft.reply_text}
                  status={selected.draft.status}
                  sentText={selected.draft.sent_text}
                  nextHref={next ? href(filter, next.email.id) : null}
                  prevHref={prev ? href(filter, prev.email.id) : null}
                />
              </>
            ) : (
              <p className="text-sm text-slate-500">No draft yet. Use &ldquo;Draft replies&rdquo; on the left.</p>
            )}
          </>
        )}
      </section>

      <aside className="min-h-0 overflow-y-auto rounded-lg border border-slate-200 bg-white p-4">
        {selected?.draft && selected.classification ? (
          <WhyPanel draft={selected.draft} classification={selected.classification} playbook={services.repos.playbook} />
        ) : (
          <p className="text-sm text-slate-500">The reasons behind each draft appear here.</p>
        )}
      </aside>
    </div>
  );
}
